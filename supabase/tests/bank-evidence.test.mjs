import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const migration=await fs.readFile(new URL('../migrations/20261107042953_bank_branch_and_private_book.sql',import.meta.url),'utf8');
const school='00000000-0000-0000-0000-000000000001', other='00000000-0000-0000-0000-000000000002', user='00000000-0000-0000-0000-000000000003';
const file=`${school}/${user}/00000000-0000-0000-0000-000000000004.jpg`;
test('bank evidence stays private, school-scoped, immutable, and retained after submission',async()=>{
 const db=new PGlite();
 await db.exec(`CREATE ROLE anon;CREATE ROLE authenticated;CREATE SCHEMA auth;CREATE SCHEMA storage;
 CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$SELECT nullif(current_setting('test.uid',true),'')::uuid$$;
 CREATE FUNCTION has_role(uuid,text) RETURNS boolean LANGUAGE plpgsql AS $$BEGIN RETURN $1=auth.uid() AND $2=current_setting('test.role',true);END$$;
 CREATE FUNCTION get_user_school_id(uuid) RETURNS uuid LANGUAGE plpgsql AS $$BEGIN RETURN nullif(current_setting('test.school',true),'')::uuid;END$$;
 CREATE FUNCTION storage.foldername(text) RETURNS text[] LANGUAGE sql AS $$SELECT string_to_array($1,'/')$$;
 CREATE TABLE bendahara_bank_accounts(id uuid PRIMARY KEY,school_id uuid);
 CREATE TABLE storage.buckets(id text PRIMARY KEY,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 CREATE TABLE storage.objects(id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,bucket_id text,name text);
 ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
 GRANT USAGE ON SCHEMA public,auth,storage TO anon,authenticated;
 GRANT SELECT,INSERT,DELETE,UPDATE ON storage.objects TO anon,authenticated;
 GRANT USAGE,SELECT ON SEQUENCE storage.objects_id_seq TO anon,authenticated;
 GRANT SELECT ON bendahara_bank_accounts TO anon,authenticated;
 `);
 await db.exec(migration);
 assert.equal((await db.query(`SELECT public FROM storage.buckets`)).rows[0].public,false);
 // Existing accounts can remain without evidence; forged cross-school paths are rejected.
 await db.exec(`INSERT INTO bendahara_bank_accounts(id,school_id) VALUES ('${user}','${school}')`);
 await assert.rejects(db.exec(`UPDATE bendahara_bank_accounts SET bank_book_path='${other}/${user}/00000000-0000-0000-0000-000000000004.jpg'`),/bank_book_school_path/);
 await db.exec(`SET ROLE anon;`);
 await assert.rejects(db.exec(`INSERT INTO storage.objects(bucket_id,name) VALUES ('bank-account-documents','${file}')`),/row-level security/);
 await db.exec(`RESET ROLE;SELECT set_config('test.uid','${user}',false),set_config('test.school','${school}',false),set_config('test.role','bendahara',false);SET ROLE authenticated;`);
 await db.exec(`INSERT INTO storage.objects(bucket_id,name) VALUES ('bank-account-documents','${file}')`);
 assert.equal((await db.query(`SELECT * FROM storage.objects`)).rows.length,1);
 await assert.rejects(db.exec(`INSERT INTO storage.objects(bucket_id,name) VALUES ('bank-account-documents','${other}/${user}/00000000-0000-0000-0000-000000000005.jpg')`),/row-level security/);
 assert.equal((await db.query(`UPDATE storage.objects SET name='changed' RETURNING id`)).rows.length,0);
 await db.exec(`RESET ROLE;UPDATE bendahara_bank_accounts SET bank_branch='KCP Purwokerto',bank_book_path='${file}';SET ROLE authenticated;`);
 assert.equal((await db.query(`DELETE FROM storage.objects RETURNING id`)).rows.length,0);
 await db.exec(`SELECT set_config('test.school','${other}',false)`);
 assert.equal((await db.query(`SELECT * FROM storage.objects`)).rows.length,0);
 await db.exec(`SELECT set_config('test.role','super_admin',false)`);
 assert.equal((await db.query(`SELECT * FROM storage.objects`)).rows.length,1);
 await db.exec(`RESET ROLE;SET ROLE anon;`);
 assert.equal((await db.query(`SELECT * FROM storage.objects`)).rows.length,0);
 await db.close();
});
